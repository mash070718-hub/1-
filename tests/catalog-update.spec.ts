import { expect, test } from '@playwright/test';
import { CATALOG, CATALOG_METADATA } from '../src/lib/catalog';
import { createCatalogLibrary, createEntry, createMirrorEvaluation } from '../src/lib/library';
import { draftKey, mockCloud } from './mock-cloud';

test('a newer catalog appears for visitors and old admin drafts without publishing or overwriting evaluations', async ({ browser }) => {
  const addedIdentity = CATALOG.filter(entry => entry.kind === 'identity').at(-1)!;
  const addedEgo = CATALOG.filter(entry => entry.kind === 'ego').at(-1)!;
  const addedIds = [addedIdentity.id, addedEgo.id];
  const old = createCatalogLibrary();
  old.entries = old.entries.filter(entry => !addedIds.includes(entry.id));
  const evaluated = old.entries.find(entry => entry.kind === 'identity')!;
  evaluated.overallTier = 'A'; evaluated.tiers.story = 'S'; evaluated.tiers.railway = 'B';
  evaluated.scores = { story: 18, railway: 7.5 };
  evaluated.artwork = 'uptie1';
  evaluated.description = '공개된 기존 평가';
  const deck = { ...createEntry('deck'), name: '기존 덱', memberIds: [evaluated.id], formationCode: 'KEEP-1' };
  old.entries.push(deck); evaluated.deckIds = [deck.id];
  old.mirrorArchive = { decks: [], evaluations: [{ ...createMirrorEvaluation(evaluated.id), tier: 'B', score: 27, description: '거울던전 보존' }] };
  const store = { data: structuredClone(old), revision: 5 };
  const visitorContext = await browser.newContext();
  const adminContext = await browser.newContext();
  await mockCloud(visitorContext, store); await mockCloud(adminContext, store);
  const visitor = await visitorContext.newPage();
  await visitor.goto('/');
  await expect(visitor.getByRole('tab', { name: /^인격/ })).toContainText(String(CATALOG_METADATA.counts.identity));
  await visitor.getByPlaceholder('이름, 수감자, 태그로 검색').fill(`${addedIdentity.name} ${addedIdentity.sinner}`);
  const newCard = visitor.getByRole('button', { name: `${addedIdentity.name} ${addedIdentity.sinner} 상세 보기`, exact: true });
  await expect(newCard.locator('img')).toHaveAttribute('src', addedIdentity.thumbnail);
  await expect.poll(() => newCard.locator('img').evaluate((img: HTMLImageElement) => img.complete && img.naturalWidth > 0)).toBe(true);
  await newCard.click();
  await expect(visitor.locator('.detail-overall-tier')).toContainText('미평가');
  await expect(visitor.locator('.detail-tier-cell strong')).toHaveText(['—', '—', '—', '—']);
  await expect(visitor.getByRole('button', { name: '기록 수정', exact: true })).toHaveCount(0);
  await visitor.getByRole('dialog').getByRole('button', { name: '닫기', exact: true }).click();
  await visitor.getByRole('tab', { name: /^E\.G\.O\./ }).click();
  await visitor.getByPlaceholder('이름, 수감자, 태그로 검색').fill(`${addedEgo.name} ${addedEgo.sinner}`);
  await expect(visitor.getByRole('button', { name: `${addedEgo.name} ${addedEgo.sinner} 상세 보기`, exact: true }).locator('img')).toHaveAttribute('src', addedEgo.thumbnail);
  const draft = structuredClone(old);
  draft.entries.find(entry => entry.id === evaluated.id)!.description = '아직 게시하지 않은 내 메모';
  await adminContext.addInitScript(({ key, draft }) => {
    localStorage.setItem(key, JSON.stringify(draft));
    sessionStorage.setItem('library-of-limbus:admin-session', JSON.stringify({ access_token: 'admin-test-token', refresh_token: 'refresh', expires_at: Date.now() / 1000 + 3600 }));
  }, { key: draftKey, draft });
  const admin = await adminContext.newPage();
  await admin.goto('/');
  await expect(admin.getByRole('button', { name: '로그아웃', exact: true })).toBeVisible();
  await expect(admin.getByRole('tab', { name: /^인격/ })).toContainText(String(CATALOG_METADATA.counts.identity));
  await admin.getByPlaceholder('이름, 수감자, 태그로 검색').fill(`${evaluated.name} ${evaluated.sinner}`);
  await admin.getByRole('button', { name: `${evaluated.name} ${evaluated.sinner} 상세 보기`, exact: true }).click();
  await expect(admin.getByRole('dialog')).toContainText('아직 게시하지 않은 내 메모');
  await expect(admin.locator('.detail-overall-tier')).toContainText('A 티어');
  await expect(admin.locator('.detail-tier-cell strong')).toHaveText(['S', '—', '—', 'B']);
  await admin.getByRole('button', { name: '기록 수정', exact: true }).click();
  await admin.getByRole('button', { name: '기록 저장', exact: true }).click();
  const saved = await admin.evaluate(key => JSON.parse(localStorage.getItem(key)!), draftKey);
  expect(saved.entries.find((entry: { id: string }) => entry.id === evaluated.id)).toMatchObject({ artwork: 'uptie1', scores: evaluated.scores, overallTier: 'A', tiers: evaluated.tiers, deckIds: [deck.id], description: '아직 게시하지 않은 내 메모' });
  expect(saved.entries.find((entry: { id: string }) => entry.id === deck.id)).toEqual(deck);
  expect(saved.mirrorArchive).toEqual(old.mirrorArchive);
  expect(addedIds.every(id => saved.entries.some((entry: { id: string }) => entry.id === id))).toBe(true);
  expect(store.data).toEqual(old);
  expect(store.revision).toBe(5);
  await visitorContext.close(); await adminContext.close();
});
