import { readFile } from 'node:fs/promises';
import { expect, test } from '@playwright/test';
import { createCatalogLibrary, createMirrorEvaluation, type LibraryData } from '../src/lib/library';
import { draftKey, mockCloud } from './mock-cloud';

test.use({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });

test('overall A and story S stay independent through editing, backup, reload and visitor publication', async ({ page, browser }, testInfo) => {
  const data = createCatalogLibrary();
  const identity = data.entries.find(entry => entry.kind === 'identity')!;
  delete identity.overallTier; // A real old entry before the overall tier existed.
  identity.tiers.story = 'A'; identity.tiers.railway = 'S';
  identity.description = '종합과 스토리를 따로 평가';
  identity.scores = { story: 18, luxcavation: 8, simulation: 22, railway: 7 };
  data.mirrorArchive = { decks: [], evaluations: [{ ...createMirrorEvaluation(identity.id), tier: 'B', score: 25 }] };
  const store = { data, revision: 1 };
  await mockCloud(page.context(), store);
  await page.addInitScript(() => sessionStorage.setItem('library-of-limbus:admin-session', JSON.stringify({
    access_token: 'admin-test-token', refresh_token: 'refresh', expires_at: Date.now() / 1000 + 3600,
  })));
  await page.goto('/');
  await expect(page.getByRole('button', { name: '로그아웃', exact: true })).toBeVisible();
  const name = `${identity.name} ${identity.sinner}`;
  const card = page.getByRole('button', { name: `${name} 상세 보기`, exact: true });
  const overall = page.getByRole('combobox', { name: `${name} 종합 티어`, exact: true });
  await page.getByPlaceholder('이름, 수감자, 태그로 검색').fill(name);
  await expect(page.getByRole('tab', { name: '종합', exact: true })).toHaveAttribute('aria-selected', 'true');
  await expect(overall).toHaveValue('A');
  await overall.selectOption('B');
  const saved = (): Promise<LibraryData> => page.evaluate(key => JSON.parse(localStorage.getItem(key)!), draftKey);
  expect((await saved()).entries.find(entry => entry.id === identity.id)).toMatchObject({ overallTier: 'B', tiers: { story: 'A', railway: 'S' } });
  await card.click();
  await page.getByRole('button', { name: '기록 수정', exact: true }).click();
  await page.getByRole('combobox', { name: '종합 티어', exact: true }).selectOption('A');
  await page.getByRole('combobox', { name: '스토리 티어', exact: true }).selectOption('S');
  await page.getByRole('spinbutton', { name: '스토리 점수', exact: true }).fill('20');
  await page.getByRole('button', { name: '기록 저장', exact: true }).click();
  await page.reload();
  await page.getByPlaceholder('이름, 수감자, 태그로 검색').fill(name);
  await expect(overall).toHaveValue('A');
  await card.click();
  await expect(page.locator('.detail-overall-tier')).toContainText('종합 티어: A 티어');
  await expect(page.locator('.detail-tier-cell').filter({ hasText: '스토리' })).toContainText('S');
  await expect(page.getByRole('region', { name: '인격 종합점수' })).toContainText('82 / 100점');
  await page.getByRole('dialog').screenshot({ path: testInfo.outputPath('independent-tiers-mobile.png') });
  await page.getByRole('dialog').getByRole('button', { name: '닫기', exact: true }).click();
  await page.getByRole('navigation', { name: '도서관 메뉴' }).getByRole('button', { name: '티어리스트', exact: true }).click();
  await expect(page.locator('.tier-row[data-tier="A"]').getByRole('button', { name: `${name} 상세 보기`, exact: true })).toBeVisible();
  await page.getByRole('tab', { name: '스토리', exact: true }).click();
  await expect(page.locator('.tier-row[data-tier="S"]').getByRole('button', { name: `${name} 상세 보기`, exact: true })).toBeVisible();
  await card.click();
  await page.getByRole('combobox', { name: '스토리 티어', exact: true }).selectOption('D');
  await expect(page.locator('.detail-overall-tier')).toContainText('A 티어');
  await page.getByRole('combobox', { name: '스토리 티어', exact: true }).selectOption('S');
  await page.getByRole('dialog').getByRole('button', { name: '닫기', exact: true }).click();
  const current = await saved();
  expect(current.entries.find(entry => entry.id === identity.id)).toMatchObject({ overallTier: 'A', tiers: { story: 'S', railway: 'S' } });
  expect(current.mirrorArchive).toEqual(data.mirrorArchive);
  await page.getByRole('button', { name: '백업과 복원', exact: true }).click();
  const downloading = page.waitForEvent('download');
  await page.getByRole('button', { name: '백업 다운로드', exact: true }).click();
  const backup = await readFile((await (await downloading).path())!, 'utf8');
  expect(JSON.parse(backup).entries.find((entry: { id: string }) => entry.id === identity.id)).toMatchObject({ overallTier: 'A', tiers: { story: 'S' } });
  await page.getByLabel('백업 파일 선택').setInputFiles({ name: 'independent-tiers.json', mimeType: 'application/json', buffer: Buffer.from(backup) });
  await page.getByRole('button', { name: '가져오기 확인', exact: true }).click();
  await page.getByRole('button', { name: '게시하기', exact: true }).click();
  await page.getByRole('button', { name: '공개 게시 확인', exact: true }).click();
  await expect(page.getByRole('button', { name: '게시하기', exact: true })).toBeDisabled();
  const context = await browser.newContext();
  await mockCloud(context, store);
  const visitor = await context.newPage();
  await visitor.goto('/');
  await visitor.getByPlaceholder('이름, 수감자, 태그로 검색').fill(name);
  await expect(visitor.locator('.card-footer')).toContainText('종합 A 티어');
  await visitor.getByRole('button', { name: `${name} 상세 보기`, exact: true }).click();
  await expect(visitor.locator('.detail-overall-tier')).toContainText('A 티어');
  await expect(visitor.locator('.detail-tier-cell').filter({ hasText: '스토리' })).toContainText('S');
  await expect(visitor.getByRole('button', { name: '기록 수정', exact: true })).toHaveCount(0);
  await context.close();
});
